"""T1 GATE — WALK-FORWARD CALIBRATION LAYER (pre-registered, ONE config).

Motivation (D67-R2/D69 convergent finding): shipped probabilities look globally
UNDERCONFIDENT — fitted logistic scale 6.65 vs shipped 7.2 on the headline CSV
(a,b free), uniform +0.07 favorite-side probability shortfall across strength
quintiles, home-bias intercept -0.07..-0.13.  Prior-evidence CONFLICT to
adjudicate: D61's link test found NO headroom (hindsight-optimal scale exactly
7.20) on PRE-carry margins with shape-only variants, while D67's probe found
6.65 with (a,b) free on the headline CSV.  This gate decides on the CURRENT
shipped margins (fit_production with D62 carry) with honest WALK-FORWARD
fitting.

CONSTRUCTION (one config, no sweeps):
    p_cal = sigmoid(a + b * margin / 7.2)
  (a,b) fit by unpenalized logistic regression WALK-FORWARD on the trailing
  2 seasons of (shipped-margin, outcome) pairs generated by THIS run (current
  season + immediately previous season, outcomes strictly before the refit
  date), refit MONTHLY (first game of each new calendar month), burn-in
  (a,b)=(0,1) until >= 800 trailing games are available.

CONTROL: same-run replication of shipped production (the prod_by_season.py
capstone loop with the D62 carry inside fit_production; margins captured from
model.margin(...) directly, dead flags NOT passed, b2b flags passed) —
cross-checked vs data/capstone_pergame_carry2.csv (expected max |dp| ~1e-14).

GATE: paired bootstrap 2000x, 95% CI on per-game logloss delta
(ctl - cal, positive = calibration better), pooled over the 3 seasons.
PASS iff the pooled CI excludes 0 (burn-in games included: delta=0 there).

RULES HONORED: DuckDB read_only=True; new file scripts/t1_calibration.py only;
nothing in nbapred/ or existing scripts edited; market p is NEVER an input to
the model or the calibration fit — it only joins for evaluation subsets.

Run:  python scripts/t1_calibration.py                 (full 3-season walk-forward)
      python scripts/t1_calibration.py --analyze-only  (re-run gate analysis)
"""
import sys, os, json, csv, warnings
import datetime as _dt
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np

from nbapred.db import connect
from nbapred.model.production import SCALE, sigmoid, fit_production, _prev_season

SEASONS = ("2023-24", "2024-25", "2025-26")
BURN_IN_MIN = 800          # pre-registered burn-in threshold (trailing games)
HEAVY = 0.35               # prior convention (D61 intersection subset)
EARLY_GP = 20              # prior convention (ba_portfolio early split)
N_BOOT = 2000
BOOT_SEED = 7

OUT_CSV = ROOT / "data" / "t1_calibration_pergame.csv"
OUT_JSON = ROOT / "data" / "t1_calibration_results.json"
BASE_CSVS = [ROOT / "data" / "capstone_pergame_carry2.csv",
             ROOT / "data" / "capstone_pergame_carry.csv"]


# ---- closure extraction: the SAME fitted composition production used --------

def _freevars(bound):
    fn = bound.__func__
    return dict(zip(fn.__code__.co_freevars,
                    (c.cell_contents for c in fn.__closure__)))


def extract_comp(model):
    fv = _freevars(model.margin)
    assert "comp" in fv, "closure drift: comp not found in model.margin"
    return fv["comp"]


# ---- walk-forward logistic calibration --------------------------------------

def fit_logistic(x, y, iters=60, tol=1e-12):
    """Unpenalized 2-param logistic MLE via Newton-Raphson.
    x = margin/SCALE, y in {0,1}. Deterministic. Returns (a, b)."""
    X = np.c_[np.ones(len(x)), np.asarray(x, float)]
    y = np.asarray(y, float)
    w = np.array([0.0, 1.0])            # start at the shipped identity
    for _ in range(iters):
        z = np.clip(X @ w, -30, 30)
        p = 1.0 / (1.0 + np.exp(-z))
        g = X.T @ (y - p)
        wd = p * (1 - p)
        H = X.T @ (X * wd[:, None])
        try:
            step = np.linalg.solve(H, g)
        except np.linalg.LinAlgError:
            break
        w = w + step
        if np.abs(step).max() < tol:
            break
    return float(w[0]), float(w[1])


class Calibrator:
    """Trailing-2-season monthly-refit walk-forward calibration state."""

    def __init__(self):
        self.pool = []                  # (season, date, margin, y)
        self.a, self.b = 0.0, 1.0
        self.active = False
        self.last_refit_month = None
        self.refits = []                # trajectory for the report

    def maybe_refit(self, season, gd):
        key = (gd.year, gd.month)
        if key == self.last_refit_month:
            return
        self.last_refit_month = key
        allowed = {season, _prev_season(season)}
        pairs = [(m, y) for (s, d, m, y) in self.pool
                 if s in allowed and d < gd]
        n = len(pairs)
        if n >= BURN_IN_MIN:
            x = np.array([m for m, _ in pairs]) / SCALE
            yy = np.array([y for _, y in pairs])
            self.a, self.b = fit_logistic(x, yy)
            self.active = True
        else:
            self.a, self.b = 0.0, 1.0
            self.active = False
        self.refits.append(dict(
            season=season, date=str(gd)[:10], n_trailing=n,
            active=self.active, a=round(self.a, 5), b=round(self.b, 5),
            implied_scale=(round(SCALE / self.b, 3) if self.active else None)))

    def p(self, margin):
        return float(sigmoid(self.a + self.b * margin / SCALE))

    def add(self, season, gd, margin, y):
        self.pool.append((season, gd, float(margin), int(y)))


# ---- walk-forward capstone loop (copied from scripts/prod_by_season.py) -----

def season_run(season, cal):
    con = connect(read_only=True)
    pm = con.execute("""SELECT game_id, team_id, player_id, seconds/60.0 AS mins
        FROM player_game_stats WHERE game_id LIKE '002%' AND seconds>0""").fetchdf()
    played = {(g, t): set(grp.player_id)
              for (g, t), grp in pm.groupby(["game_id", "team_id"])}
    meta = con.execute("""SELECT game_id, team_id, team_abbrev, matchup, wl, game_date
        FROM nba_games WHERE season=? AND game_id LIKE '002%' AND wl IS NOT NULL
        ORDER BY game_date""", [season]).fetchdf()
    mkt = {(str(r[0])[:10], r[1], r[2]): r[3] for r in con.execute(
        "SELECT game_date, home, away, p_home_spread FROM odds_market WHERE season_end=?",
        [int(season[:4]) + 1]).fetchall()}
    by, order = {}, []
    for x in meta.itertuples():
        if x.game_id not in by:
            order.append(x.game_id)
        by.setdefault(x.game_id, []).append(x)
    if os.environ.get("T1_SMOKE"):          # dev harness check only
        order = order[:int(os.environ["T1_SMOKE"])]
    tdates = {}
    for x in meta.itertuples():
        d = x.game_date.date() if hasattr(x.game_date, "date") else x.game_date
        tdates.setdefault(x.team_id, set()).add(d)

    def b2b(tid, d):
        return (d - _dt.timedelta(days=1)) in tdates.get(tid, set())

    # games-played counts (for the early/late split only; dead flags NOT used)
    hist = {}
    for x in meta.itertuples():
        d = x.game_date.date() if hasattr(x.game_date, "date") else x.game_date
        hist.setdefault(x.team_id, []).append((d, x.wl == "W"))
    for t in hist:
        hist[t].sort()

    def gp(tid, d):
        return sum(1 for (dd, _) in hist.get(tid, []) if dd < d)

    rows_out = []
    model = comp = None
    last = None
    for gid in order:
        recs = by[gid]
        if len(recs) != 2:
            continue
        m = recs[0].matchup
        host = m.split("@")[-1].strip() if "@" in m else m.split("vs.")[0].strip()
        h = next((x for x in recs if x.team_abbrev == host), None)
        a = next((x for x in recs if x.team_abbrev != host), None)
        if not h or not a:
            continue
        gd = h.game_date.date() if hasattr(h.game_date, "date") else h.game_date
        if last is None or (gd - last).days >= 7:
            model = fit_production(con, season, before=gd, w_comp=0.7)
            comp = extract_comp(model)
            last = gd
        cal.maybe_refit(season, gd)          # monthly (a,b) refit, PIT: d < gd
        pmv = mkt.get((str(gd)[:10], h.team_abbrev, a.team_abbrev))
        if pmv is None:
            continue
        outs = {}
        for t in (h.team_id, a.team_id):
            pl = played.get((gid, t), set())
            outs[t] = {p for p, d0 in comp.players.items()
                       if d0["team_id"] == t and (gd - d0["last_played"]).days <= 12
                       and p not in pl}
        yv = int(h.wl == "W")
        margin = model.margin(h.team_id, a.team_id, outs[h.team_id],
                              outs[a.team_id], gd,
                              b2b_home=b2b(h.team_id, gd),
                              b2b_away=b2b(a.team_id, gd))
        p_ctl = float(sigmoid(margin / SCALE))       # == model.p_home exactly
        p_cal = cal.p(margin)
        cal.add(season, gd, margin, yv)              # outcome enters the pool;
        #  used only at the NEXT monthly refit (d < gd filter) — PIT safe
        rows_out.append([season, gid, str(gd)[:10], h.team_abbrev, a.team_abbrev,
                         yv, float(margin), p_ctl, p_cal, float(pmv),
                         round(cal.a, 6), round(cal.b, 6), int(cal.active),
                         gp(h.team_id, gd), gp(a.team_id, gd),
                         len(outs[h.team_id]), len(outs[a.team_id])])
    con.close()
    n_active = sum(r[12] for r in rows_out)
    print(f"[{season}] games={len(rows_out)} cal_active={n_active} "
          f"burn_in={len(rows_out) - n_active} pool={len(cal.pool)}", flush=True)
    return rows_out


# ---- gate analysis ----------------------------------------------------------

def pg_ll(y, p, eps=1e-15):
    p = np.clip(np.asarray(p, float), eps, 1 - eps)
    y = np.asarray(y, float)
    return -(y * np.log(p) + (1 - y) * np.log(1 - p))


def boot(delta, n_boot=N_BOOT, seed=BOOT_SEED):
    delta = np.asarray(delta, float)
    if len(delta) == 0:
        return dict(n=0, mean=None, lo=None, hi=None, verdict="NS")
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(delta), size=(n_boot, len(delta)))
    means = delta[idx].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    verdict = "PASS" if lo > 0 else ("FAIL" if hi < 0 else "NS")
    return dict(n=int(len(delta)), mean=float(delta.mean()), lo=float(lo),
                hi=float(hi), verdict=verdict)


def analyze(refits):
    import pandas as pd
    df = pd.read_csv(OUT_CSV, dtype={"game_id": str})
    d = pg_ll(df.y, df.p_ctl) - pg_ll(df.y, df.p_cal)   # + = calibration better

    res = {"config": dict(
        construction="p_cal = sigmoid(a + b*margin/7.2); (a,b) logistic MLE, "
                     "walk-forward, trailing 2 seasons (same-run pairs), "
                     "monthly refit, burn-in (0,1) until >=800 trailing games",
        burn_in_min=BURN_IN_MIN, heavy=HEAVY, early_gp=EARLY_GP,
        gate="pooled paired bootstrap 2000x 95% CI excludes 0 (pre-registered)")}

    # control fidelity vs the shipped carry capstone CSVs
    xchk = {}
    for path in BASE_CSVS:
        if not path.exists():
            continue
        b = pd.read_csv(path, dtype={"game_id": str})
        j = b.merge(df, on=["season", "game_id"])
        per = {s: float((g.p_ctl - g.p_us).abs().max())
               for s, g in j.groupby("season")}
        xchk[path.name] = {"joined": int(len(j)), "max_dp_per_season": per}
    res["control_crosscheck"] = xchk

    # headline log-losses
    res["logloss"] = {}
    for s, g in df.groupby("season"):
        res["logloss"][s] = dict(
            ctl=round(float(pg_ll(g.y, g.p_ctl).mean()), 4),
            cal=round(float(pg_ll(g.y, g.p_cal).mean()), 4),
            mkt=round(float(pg_ll(g.y, g.p_mkt).mean()), 4),
            n=int(len(g)), cal_active_n=int(g.cal_active.sum()))
    res["logloss"]["pooled"] = dict(
        ctl=round(float(pg_ll(df.y, df.p_ctl).mean()), 4),
        cal=round(float(pg_ll(df.y, df.p_cal).mean()), 4),
        mkt=round(float(pg_ll(df.y, df.p_mkt).mean()), 4),
        n=int(len(df)), cal_active_n=int(df.cal_active.sum()))

    # ---- THE pre-registered gate ----
    pooled = boot(d)
    res["gate"] = {
        "pooled": pooled,
        "SHIP": bool(pooled["lo"] is not None and pooled["lo"] > 0),
        "per_season": {s: boot(d[(df.season == s).values]) for s in SEASONS},
    }

    # diagnostic: calibration-active games only (burn-in delta==0 dilutes pooled)
    act = (df.cal_active == 1).values
    res["active_only_report"] = {
        "pooled": boot(d[act]),
        "per_season": {s: boot(d[act & (df.season == s).values])
                       for s in SEASONS},
        "note": "report-only; the gate adjudicates on pooled incl. burn-in"}

    # ---- pre-registered report subsets (definitions verbatim bet_diagnose) --
    pick_home = (df.p_ctl > 0.5).values
    same_side = ((df.p_ctl - 0.5) * (df.p_mkt - 0.5) > 0).values
    flatter = same_side & (np.abs(df.p_mkt - 0.5) > np.abs(df.p_ctl - 0.5)).values
    hit = np.where(pick_home, df.y == 1, df.y == 0)
    fl_lands = flatter & hit
    mkt_heavy = (np.abs(df.p_mkt - 0.5) > HEAVY).values
    us_heavy = (np.abs(df.p_ctl - 0.5) > HEAVY).values
    early = ((df.gp_home < EARLY_GP) | (df.gp_away < EARLY_GP)).values
    subs = {
        "flatter_same_side": flatter,
        "flatter_and_favorite_lands": fl_lands,
        "heavy_mkt": mkt_heavy,
        "heavy_us": us_heavy,
        "heavy_mkt_not_us": mkt_heavy & ~us_heavy,
        "heavy_both": mkt_heavy & us_heavy,
        "early_either_gp_lt20": early,
        "late_both_gp_ge20": ~early,
    }
    res["subsets"] = {k: boot(d[v]) for k, v in subs.items()}
    res["subsets_per_season_flatter_lands"] = {
        s: boot(d[fl_lands & (df.season == s).values]) for s in SEASONS}

    # (a,b) trajectory + summary — the adjudication evidence (D61 vs D67)
    res["refit_trajectory"] = refits
    act_r = [r for r in refits if r["active"]]
    if act_r:
        a_arr = np.array([r["a"] for r in act_r])
        b_arr = np.array([r["b"] for r in act_r])
        res["ab_summary"] = dict(
            n_refits_active=len(act_r), n_refits_total=len(refits),
            a_mean=round(float(a_arr.mean()), 4),
            a_range=[round(float(a_arr.min()), 4), round(float(a_arr.max()), 4)],
            b_mean=round(float(b_arr.mean()), 4),
            b_range=[round(float(b_arr.min()), 4), round(float(b_arr.max()), 4)],
            implied_scale_mean=round(float(SCALE / b_arr.mean()), 3),
            note="b>1 => effective scale < 7.2 (underconfidence, D67 side); "
                 "b~1,a~0 => no headroom (D61 side); a<0 => home-bias intercept")
    json.dump(res, open(OUT_JSON, "w"), indent=1)
    print(json.dumps(res, indent=1))
    return res


def main():
    if "--analyze-only" not in sys.argv:
        header = ["season", "game_id", "game_date", "home", "away", "y",
                  "margin", "p_ctl", "p_cal", "p_mkt", "cal_a", "cal_b",
                  "cal_active", "gp_home", "gp_away", "n_out_home", "n_out_away"]
        cal = Calibrator()
        all_rows = []
        for s in SEASONS:
            all_rows += season_run(s, cal)
        with open(OUT_CSV, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(header)
            w.writerows(all_rows)
        refits = cal.refits
        json.dump(refits, open(str(OUT_JSON) + ".refits.tmp", "w"))
    else:
        tmp = str(OUT_JSON) + ".refits.tmp"
        refits = (json.load(open(tmp)) if os.path.exists(tmp)
                  else json.load(open(OUT_JSON)).get("refit_trajectory", []))
    analyze(refits)


if __name__ == "__main__":
    main()
